    /// <summary>Returns the low-power encoders a GPU's generation has.</summary>
    /// <param name="vendor">The PCI vendor ID from sysfs, e.g. <c>0x8086</c>.</param>
    /// <param name="device">The PCI device ID from sysfs, e.g. <c>0x5a85</c>.</param>
    /// <returns>The support; Unknown for anything that isn't a recognised Intel GPU.</returns>
    public static LowPowerSupport LowPower(string vendor, string device)
    {
        ArgumentNullException.ThrowIfNull(device);
        if (!string.Equals(vendor, "0x8086", StringComparison.OrdinalIgnoreCase)
            || !int.TryParse(device.Replace("0x", string.Empty, StringComparison.OrdinalIgnoreCase), NumberStyles.HexNumber, CultureInfo.InvariantCulture, out var id))
        {
            return LowPowerSupport.Unknown;
        }

        return _gen8AndOlder.Contains(id) ? LowPowerSupport.None : _gen9.Contains(id) ? LowPowerSupport.H264Only : LowPowerSupport.Unknown;
    }
}
